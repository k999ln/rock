/** UI strings only: user input, provider descriptions and results are never translated. */
export const NOAH_LOCALES = ['ja', 'en', 'zh-CN', 'ko', 'es', 'ar'] as const;
export type NoahLocale = (typeof NOAH_LOCALES)[number];
export const NOAH_LANGUAGE_NAMES: Record<NoahLocale, string> = {
  ja: '日本語',
  en: 'English',
  'zh-CN': '简体中文',
  ko: '한국어',
  es: 'Español',
  ar: 'العربية',
};
export const NOAH_LOCALE_KEY = 'noah-language-v1';
export function resolveNoahLocale(languages: readonly string[]): NoahLocale {
  for (const language of languages) {
    const value = language.toLowerCase().replaceAll('_', '-');
    if (value.startsWith('zh')) return 'zh-CN';
    const base = value.split('-')[0];
    if (NOAH_LOCALES.includes(base as NoahLocale)) return base as NoahLocale;
  }
  return 'en';
}
