export function noahTranslate(
  locale: NoahLocale,
  source: string,
  values: Record<string, string | number> = {},
): string {
  const index = NOAH_LOCALES.indexOf(locale) - 1;
  if (index >= 0 && !NOAH_MESSAGES[source]) {
    const patterns: [RegExp, string, string][] = [
      [/^道具 (\d+) 個$/, '道具 {count} 個', 'count'],
      [/^([\d,]+) 人が利用$/, '{count} 人が利用', 'count'],
      [/^相手のサーバー（(.+)）$/, '相手のサーバー（{host}）', 'host'],
      [/^最後に確かめた日 (.+)$/, '最後に確かめた日 {date}', 'date'],
    ];
    for (const [pattern, key, field] of patterns) {
      const match = source.match(pattern);
      if (match) return noahTranslate(locale, key, { [field]: match[1] });
    }
    const taps = source.match(/^あと (\d+) タップ(?:（(.+)）)?$/);
    if (taps)
      return (
        noahTranslate(locale, 'あと {count} タップ', { count: taps[1] }) +
        (taps[2] ? ` (${noahTranslate(locale, taps[2])})` : '')
      );
    const setup = source.match(/^準備が必要（(.+)）$/);
    if (setup)
      return `${noahTranslate(locale, '準備が必要')} (${noahTranslate(locale, setup[1])})`;
  }
  const template =
    index < 0 ? source : (NOAH_MESSAGES[source]?.[index] ?? source);
  return template.replace(/\{(\w+)\}/g, (match, name: string) =>
    Object.hasOwn(values, name) ? String(values[name]) : match,
  );
}
