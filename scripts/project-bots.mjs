const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const read = (path) => JSON.parse(readFileSync(resolve(root, path), 'utf8'));
const header =
  '# Generated by scripts/project-bots.mjs from data/amc/project-bots.json\n';

export function projectBots() {
  const registry = read('data/amc/project-bots.json');
  const mission = read('data/mission-control.json');
  const squads = new Set(mission.squads.map((squad) => squad.id));
  const ids = new Set();
  if (
    registry.schema !== 'rock-project-bots/1' ||
    registry.repository !== 'k999ln/rock'
  )
    throw new Error('担当Bot台帳が不正です');
  for (const bot of registry.bots) {
    if (
      !/^[a-z][a-z-]+$/.test(bot.id) ||
      ids.has(bot.id) ||
      !bot.name?.trim() ||
      !bot.purpose?.trim() ||
      !bot.squads.length ||
      bot.squads.some((id) => !squads.has(id))
    )
      throw new Error('担当Botの定義が不正です');
    ids.add(bot.id);
    for (const path of [...bot.paths, ...bot.guides]) {
      if (
        relative(root, resolve(root, path)).startsWith('..') ||
        path.startsWith('/') ||
        !existsSync(resolve(root, path))
      )
        throw new Error('Botの参照が不正です: ' + path);
    }
  }
  return registry.bots;
}

