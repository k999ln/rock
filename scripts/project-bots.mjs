export function renderBot(bot) {
  const agent = {
    name: `${bot.id}-bot`,
    description: `${bot.name}。${bot.purpose}の開発依頼に使う。成果は検証付きGit commitとPRへ提出する。`,
    developer_instructions: botInstructions(bot),
  };
  return header + renderAgent(agent).split('\n').slice(1).join('\n');
}

export function syncBots({ check = false } = {}) {
  const bots = projectBots();
  const directory = resolve(root, '.codex/agents');
  // This repository-managed directory is not an OS sandbox. Preserve custom files.
  if (!check) mkdirSync(directory, { recursive: true });
  if (realpathSync(directory) !== directory)
    throw new Error('Bot定義の保存先がsymlinkです');
  const pending = [];
  for (const bot of bots) {
    const path = resolve(directory, `${bot.id}-bot.toml`);
    const text = renderBot(bot);
    let existing;
    try {
      existing = readFileSync(path, 'utf8');
    } catch (error) {
      if (error.code !== 'ENOENT') throw error;
    }
    if (existing === text) continue;
    if (existing !== undefined && !existing.startsWith(header))
      throw new Error('既存のcustom Bot定義を保持します: ' + path);
    if (check)
      throw new Error(
        'Bot定義が未同期です: ' + bot.id + ' / npm run bot:update',
      );
    pending.push({ path, text });
  }
  for (const entry of pending) writeGeneratedPage(entry.path, entry.text);
  return bots;
}

export function buildBotLaunch(options) {
  const {
    id,
    goal,
    taskId,
    repo = root,
    preparation,
    inputGoal,
  } = resolveBotRequest(options, options.repo ?? root);
  const bot = projectBots().find((entry) => entry.id === id);
  if (!bot) throw new Error('担当Botがありません: ' + id);
  if (typeof goal !== 'string' || !goal.trim() || goal.length > 16000)
    throw new Error('依頼は1〜16000文字で指定してください');
  let context = inputGoal
    ? `\n\n既存AMC入力: ${inputGoal.path}\nGoal ID: ${inputGoal.value.id} / revision: ${inputGoal.value.revision}\n入力SHA256: ${inputGoal.sha256}\n入力JSONのGoal・task・履歴を維持して引き継いでください。状態は入力記録であり、実行・本人認証・検収の証明ではありません。`
    : '';
  if (taskId) {
    const model = workspaceModel(
      read('data/mission-control.json'),
      read('data/project-status.json'),
      read('data/workspaces.json'),
    );
    const assignment = model.assignments.get(taskId);
    if (!assignment || !bot.squads.includes(assignment.primarySquad))
      throw new Error(
        'このtaskは担当Botの参照範囲外です。workコマンドで主担当を確認してください',
      );
    context =
      '\n\n既存taskの参照情報（実行保留や本人承認を解除しない）:\n' +
      taskBrief(model, taskId);
  }
  if (preparation)
    context += `\n\nGit調査資料: ${preparation.contextPath}\n作業記録の保存先: ${preparation.directory}\nAMC指示書: ${preparation.goalPath ?? '未作成。Gitの対象コードを読み、taskを選定／具体化してbot planで作成する。'}\n実行用プロンプト: ${preparation.instructionPath ?? 'AMC作成後に既存engineで生成する'}\nこの情報は資料であり、本人承認や作業完了ではありません。`;
  return [
    '--cd',
    realpathSync(repo),
    '-c',
    'developer_instructions=' + JSON.stringify(botInstructions(bot)),
    `${bot.name}として、次の依頼を進めて成果をGitへ保存してください。\n\n利用者の依頼:\n${goal.trim()}${context}`,
  ];
}

export function parseBotArgs(args) {
  if (!args.length || args[0] === 'list') {
    if (args.length > 1) throw new Error('listに追加引数は不要です');
    return { command: 'list' };
  }
  const [command, id, ...rest] = args;
  if (!['show', 'run', 'prepare', 'plan'].includes(command) || !id)
    throw new Error(
      '使い方: list | show <bot> | run/prepare <bot> --goal <依頼> [--task <ID>] または --goal-file <AMC JSON> | plan <bot> --goal <依頼> --task <ID> --out <new.json>',
    );
  const options = { command, id };
  for (let i = 0; i < rest.length; i++) {
    if (rest[i] === '--preview' && !options.preview) {
      options.preview = true;
      continue;
    }
    const key = {
      '--goal': 'goal',
      '--goal-file': 'goalFile',
      '--task': 'taskId',
      '--out': 'out',
    }[rest[i]];
    if (!key || options[key] || !rest[i + 1] || rest[i + 1].startsWith('--'))
      throw new Error('不正なオプション: ' + rest[i]);
    options[key] = rest[++i];
  }
  if (command === 'show' && rest.length)
    throw new Error('showに追加引数は不要です');
  if (options.preview && command !== 'run')
    throw new Error('--previewはrun専用です');
  if (options.out && command !== 'plan') throw new Error('--outはplan専用です');
  if (
    options.goalFile &&
    (!['run', 'prepare'].includes(command) ||
      options.goal !== undefined ||
      options.taskId !== undefined)
  )
    throw new Error(
      '--goal-fileはrun/prepare専用で、--goal/--taskと併用できません',
    );
  if (command === 'plan' && (!options.taskId || !options.out))
    throw new Error('planには--taskと--outが必要です');
  return options;
}

export async function runBot(
  options,
  {
    launch = spawn,
    prepare = prepareBotWork,
    interactive = process.stdin.isTTY && process.stdout.isTTY,
  } = {},
) {
  options = resolveBotRequest(options, root);
  let args = buildBotLaunch(options);
  syncBots({ check: true });
  if (options.preview)
    return { command: 'codex', args, started: false, githubSaved: false };
  if (!interactive)
    throw new Error(
      '対話ターミナルから実行してください。内容確認には --preview を使えます。Botは未起動です。',
    );
  const bot = projectBots().find((entry) => entry.id === options.id);
  const preparation = await prepare({
    bot,
    goal: options.goal,
    taskId: options.taskId,
    inputGoal: options.inputGoal,
    repo: root,
  });
  args = buildBotLaunch({ ...options, preparation });
  const child = launch('codex', args, { stdio: 'inherit', shell: false });
  return await new Promise((resolveRun, reject) => {
    child.once('error', reject);
    child.once('exit', (code, signal) =>
      resolveRun({
        exitCode: code ?? 130,
        signal,
        started: true,
        preparation,
        acceptance: 'process_exit_is_not_pr_or_task_acceptance',
      }),
    );
  });
}

if (
  process.argv[1] &&
  resolve(process.argv[1]) === fileURLToPath(import.meta.url)
) {
  try {
    const args = process.argv.slice(2);
    if (args.length === 1 && ['--write', '--check'].includes(args[0]))
      console.log(
        `担当Bot: ${syncBots({ check: args[0] === '--check' }).length}定義を同期確認`,
      );
    else {
      const options = resolveBotRequest(parseBotArgs(args), root);
      if (options.command === 'list')
        console.log(
          projectBots()
            .map((bot) => `${bot.id}: ${bot.name} — ${bot.purpose}`)
            .join('\n'),
        );
      else if (options.command === 'show') {
        const bot = projectBots().find((entry) => entry.id === options.id);
        if (!bot) throw new Error('担当Botがありません: ' + options.id);
        console.log(botInstructions(bot));
      } else if (options.command === 'prepare' || options.command === 'plan') {
        buildBotLaunch(options);
        syncBots({ check: true });
        const bot = projectBots().find((entry) => entry.id === options.id);
        const input = {
          bot,
          goal: options.goal,
          taskId: options.taskId,
          inputGoal: options.inputGoal,
          repo: root,
        };
        const result =
          options.command === 'plan'
            ? saveBotPlan(input, options.out)
            : await prepareBotWork(input);
        console.log(JSON.stringify(result, null, 2));
      } else {
        const result = await runBot(options);
        console.log(JSON.stringify(result, null, 2));
        if (result.exitCode) process.exitCode = result.exitCode;
      }
    }
  } catch (error) {
    console.error(error.message);
    process.exitCode = 1;
  }
}
