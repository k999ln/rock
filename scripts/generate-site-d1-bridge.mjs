import { createHash } from 'node:crypto';
import { existsSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';
import { DatabaseSync } from 'node:sqlite';

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..');
const source = join(root, 'services/sky-web/migrations');
const output = join(root, 'drizzle/0013_sky_provider_connections.sql');
const write = process.argv.includes('--write');

const sqlite = new DatabaseSync(':memory:');
const split = (sql) =>
  sql
    .split('--> statement-breakpoint')
    .map((statement) => statement.trim())
    .filter(Boolean);

for (const name of readdirSync(source).filter((entry) => entry.endsWith('.sql')).sort()) {
  for (const statement of split(readFileSync(join(source, name), 'utf8'))) {
    sqlite.exec(statement);
  }
}

const rows = sqlite
  .prepare(`
    SELECT type, name, sql
    FROM sqlite_master
    WHERE sql IS NOT NULL
      AND name NOT LIKE 'sqlite_%'
      AND name NOT LIKE '__new_%'
    ORDER BY
      CASE type WHEN 'table' THEN 0 WHEN 'index' THEN 1 WHEN 'trigger' THEN 2 ELSE 3 END,
      name
  `)
  .all();

const idempotent = (type, sql) => {
  if (type === 'table') return sql.replace(/^CREATE TABLE\s+/i, 'CREATE TABLE IF NOT EXISTS ');
  if (type === 'index') {
    return sql
      .replace(/^CREATE UNIQUE INDEX\s+/i, 'CREATE UNIQUE INDEX IF NOT EXISTS ')
      .replace(/^CREATE INDEX\s+/i, 'CREATE INDEX IF NOT EXISTS ');
  }
  if (type === 'trigger') return sql.replace(/^CREATE TRIGGER\s+/i, 'CREATE TRIGGER IF NOT EXISTS ');
  throw new Error(`unsupported sqlite object type: ${type}`);
};

const provenance = readdirSync(source)
  .filter((entry) => entry.endsWith('.sql'))
  .sort()
  .map((name) => `${name}:${createHash('sha256').update(readFileSync(join(source, name))).digest('hex')}`)
  .join('\n');
const provenanceDigest = createHash('sha256').update(provenance).digest('hex');

const header = [
  '-- Generated by scripts/generate-site-d1-bridge.mjs.',
  '-- Sites D1 applies this single full-schema bridge for both empty databases and',
  '-- the existing production database, where these objects already exist.',
  `-- Source lineage digest: ${provenanceDigest}`,
].join('\n');
const generated = `${header}\n${rows
  .map(({ type, sql }) => `${idempotent(type, sql)};`)
  .join('\n--> statement-breakpoint\n')}\n`;

if (write) {
  writeFileSync(output, generated);
  process.stdout.write(`${output}\n`);
} else if (!existsSync(output) || readFileSync(output, 'utf8') !== generated) {
  process.stderr.write('drizzle/0013_sky_provider_connections.sql is stale; run npm run db:site-bridge\n');
  process.exitCode = 1;
}
