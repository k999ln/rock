import assert from 'node:assert/strict';
import test from 'node:test';
import { cp, mkdir, mkdtemp, readFile, readdir, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';

void test('offline npm pack builds a fresh entry and fails closed if the build is unavailable', { timeout: 30000 }, async t => {
  const dir = await mkdtemp(join(tmpdir(), 'sky-sdk-prepack-'));
  t.after(() => rm(dir, { recursive: true, force: true }));
  const sdk = fileURLToPath(new URL('../toolkits/sky-tool-sdk/', import.meta.url));
  const archive = fileURLToPath(new URL('../public/toolkits/rockstaros-sky-tool-sdk-0.1.5.tgz', import.meta.url));
  const source = join(dir, 'source'), unpacked = join(dir, 'unpacked'), output = join(dir, 'output');
  await cp(sdk, source, { recursive: true, filter: path => !path.includes('/dist/') && !path.endsWith('/dist') });
  await mkdir(unpacked); await mkdir(output);
  const env = { ...process.env, npm_config_cache: join(dir, 'cache'), npm_config_userconfig: join(dir, 'user.conf'), npm_config_globalconfig: join(dir, 'global.conf') };
  await writeFile(env.npm_config_userconfig, ''); await writeFile(env.npm_config_globalconfig, '');
  const run = (command, args, cwd) => spawnSync(command, args, { cwd, env, encoding: 'utf8', timeout: 15000 });
  const pack = cwd => run('npm', ['pack', '--offline', '--json', '--pack-destination', output], cwd);
  const fresh = pack(source); assert.equal(fresh.status, 0, fresh.stderr);
  const packed = join(output, JSON.parse(fresh.stdout)[0].filename);
  const list = run('tar', ['-tzf', packed], dir); assert.equal(list.status, 0, list.stderr);
  assert.match(list.stdout, /package\/dist\/index\.mjs/);
  const consumer = join(dir, 'consumer'); await mkdir(consumer);
  await writeFile(join(consumer, 'package.json'), '{"private":true,"type":"module"}');
  const install = run('npm', ['install', '--offline', '--ignore-scripts', '--no-audit', '--no-fund', packed], consumer);
  assert.equal(install.status, 0, install.stderr);
  const imported = run(process.execPath, ['--input-type=module', '-e', 'import { createSkyToolApp } from "@rockstaros/sky-tool-sdk"; if (typeof createSkyToolApp !== "function" || !import.meta.resolve("@rockstaros/sky-tool-sdk").endsWith("/dist/index.mjs")) process.exit(1)'], consumer);
  assert.equal(imported.status, 0, imported.stderr);
  const extract = run('tar', ['-xzf', archive, '-C', unpacked], dir); assert.equal(extract.status, 0, extract.stderr);
  await rm(join(unpacked, 'package/dist'), { recursive: true });
  const repack = pack(join(unpacked, 'package')); assert.equal(repack.status, 0, repack.stderr);
  assert.deepEqual(await readFile(join(unpacked, 'package/dist/index.mjs')), await readFile(join(unpacked, 'package/src/index.mjs')));
  const repackList = run('tar', ['-tzf', join(output, JSON.parse(repack.stdout)[0].filename)], dir);
  assert.equal(repackList.status, 0, repackList.stderr); assert.match(repackList.stdout, /package\/dist\/index\.mjs/);
  await rm(join(output, JSON.parse(repack.stdout)[0].filename));
  await rm(join(source, 'src/index.mjs'));
  const brokenSource = pack(source); assert.notEqual(brokenSource.status, 0);
  assert.deepEqual(await readdir(output), []);
  const missingBuildFixture = join(dir, 'missing-build');
  await cp(join(unpacked, 'package'), missingBuildFixture, { recursive: true });
  assert.deepEqual(await readFile(join(missingBuildFixture, 'src/index.mjs')), await readFile(join(missingBuildFixture, 'dist/index.mjs')));
  await rm(join(missingBuildFixture, 'build.mjs'));
  const missingBuild = pack(missingBuildFixture); assert.notEqual(missingBuild.status, 0);
  assert.match(missingBuild.stderr, /build\.mjs/);
  assert.deepEqual(await readdir(output), []);
});
